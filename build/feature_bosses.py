"""Feature 3: every gym leader, rocket leader (Giovanni), Elite Four member and the Champion
fields a 6-Pokemon team. Teams are upgraded with cross-generation (gen 1-9) Pokemon themed to
each boss, but each boss's ACE (last/highest-level mon) is kept as its signature Gen-1 species.

Uses trainer structType 2 (held item + default level-up moves): safe, legal movesets are
auto-generated by the game, and the ace carries a strong held item."""
import romlib, gamedata

TR_STRIDE=40
def norm(s): return "".join(c for c in s.upper() if c.isalnum())

def build_resolver(rom):
    """normalized name -> lowest species index (so 'Charizard' resolves to the base #6, not a Mega form)."""
    m={}
    for i in range(1, gamedata.N):
        nm=gamedata.spname(rom,i)
        if not nm or nm.startswith("?"): continue
        n=norm(nm)
        if n and n not in m: m[n]=i
    return m

def resolve(resolver, name):
    n=norm(name)
    if n in resolver: return resolver[n]
    # try progressive truncation (ROM truncates long names to ~10 chars)
    for L in range(len(n),5,-1):
        for k,v in resolver.items():
            if k[:L]==n[:L] and abs(len(k)-len(n))<=2:
                return v
    return None

