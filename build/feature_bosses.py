def item_id(rom, name):
    try:
        ist=rom.tables["data.items.stats"]["addr"]
    except KeyError:
        return 0
    # data.items.stats: [name""14 ...]; find name field. Item name width 14 in FRLG.
    for i in range(800):
        nm=rom.read_name(ist + i*44, 14)  # FRLG item struct stride 44, name at offset 0
        if norm(nm)==norm(name): return i
    return 0

import struct
def apply(rom, verbose=True):
    resolver = build_resolver(rom)
    lefto = item_id(rom, ACE_ITEM) or 0
    sitrus = item_id(rom, SUB_ITEM) or 0
    IV = 255  # -> max IVs (challenging bosses), matches Champion's vanilla value
    TR = rom.tables["data.trainers.stats"]["addr"]
    alldefs = boss_defs() + champion_defs()
    count_written = 0
    bad = []
    for d in alldefs:
        team = [resolve(resolver, nm) for nm in d["team"]]
        if any(s is None for s in team):
            bad.append(d["name"]); continue
        ace = team[-1]
        if ace > 151:
            bad.append(d["name"]+":ace_not_gen1"); continue
        # the mega mon holds its stone (others: ace=Leftovers, rest=Sitrus)
        mega_sp = None; mega_stone = 0
        if d.get("mega"):
            mega_sp = resolve(resolver, d["mega"][0]); mega_stone = d["mega"][1]
            if mega_sp not in team:
                bad.append(d["name"]+":mega_not_in_team"); continue
        blob = bytearray()
        for k, (sp, lv) in enumerate(zip(team, d["lv"])):
            if mega_sp is not None and sp == mega_sp:
                item = mega_stone
            elif k == len(team)-1:
                item = lefto
            else:
                item = sitrus
            blob += struct.pack("<HHHH", IV, lv, sp, item)
        off = rom.alloc(len(blob))
        rom.data[off:off+len(blob)] = blob
        for tid in d["ids"]:
            o = TR + tid*TR_STRIDE
            rom.wu8(o+0x00, 2)        # structType 2 = held item + default level-up moves
            rom.wu8(o+0x18, 0)        # single battle
            rom.wu8(o+0x20, 6)        # party count = 6
            rom.wptr(o+0x24, off)     # party pointer -> new team
            # CFRU: a trainer only Mega Evolves if its trainer-items contain the Mega Ring (the AI
            # equivalent of the player's key stone). FindTrainerKeystone scans item1..4 @0x10 for 353.
            if mega_sp is not None:
                slots = [o+0x10+k*2 for k in range(4)]
                free = next((s for s in slots if rom.u16(s)==0), slots[-1])  # free slot, else replace item4
                rom.wu16(free, MEGA_RING_ITEM)
            count_written += 1
    if verbose:
        print("[bosses] upgraded %d boss trainer slots to 6-mon teams (%d definitions)"
              % (count_written, len(alldefs)))
        if bad: print("[bosses] PROBLEM defs:", bad)
    return dict(written=count_written, bad=bad)

def validate(rom):
    resolver=build_resolver(rom)
    alldefs=boss_defs()+champion_defs()
    problems=[]
    for d in alldefs:
        for nm in d["team"]:
            idx=resolve(resolver,nm)
            if idx is None: problems.append((d["name"],nm,"UNRESOLVED"))
        ace=resolve(resolver,d["team"][-1])
        if ace is None or ace>151:
            problems.append((d["name"],d["team"][-1],"ACE_NOT_GEN1 idx=%s"%ace))
        if len(d["team"])!=6 or len(d["lv"])!=6:
            problems.append((d["name"],"","TEAM_SIZE!=6"))
    return problems

